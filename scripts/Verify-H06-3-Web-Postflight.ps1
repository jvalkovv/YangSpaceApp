[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidatePattern('^[0-9a-f]{40}$')]
    [string]$CommitSha,

    [Parameter(Mandatory = $true)]
    [string]$EvidenceDirectory,

    [string]$Work = 'D:\GitHub\YangSpaceApp-F2b-H06.3-20261120'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$GitExe = (Get-Command git.exe -CommandType Application -ErrorAction Stop | Select-Object -First 1).Source
$ExpectedBranch = 'feat/yangspace-f2b-h06-3-public-discovery-ux-20261120'
$Evidence = (Resolve-Path -LiteralPath $EvidenceDirectory).Path.TrimEnd('\')
$Work = (Resolve-Path -LiteralPath $Work).Path

$manifest = Join-Path $Evidence 'manifest.txt'
$hashFile = Join-Path $Evidence 'manifest.sha256'
if (-not (Test-Path -LiteralPath $manifest -PathType Leaf) -or
    -not (Test-Path -LiteralPath $hashFile -PathType Leaf)) {
    throw 'H06_3_POSTFLIGHT_MANIFEST_MISSING'
}
$expectedHash = (Get-Content -LiteralPath $hashFile -Raw).Trim().ToLowerInvariant()
$actualHash = (Get-FileHash -LiteralPath $manifest -Algorithm SHA256).Hash.ToLowerInvariant()
if ($expectedHash -notmatch '^[0-9a-f]{64}$' -or $actualHash -cne $expectedHash) {
    throw 'H06_3_POSTFLIGHT_MANIFEST_SHA256_MISMATCH'
}
Write-Host 'POSTFLIGHT_MANIFEST_SHA256=PASS'

$rawRows = @(Get-Content -LiteralPath $manifest)

# Backward-compatible normalization for evidence generated by the previous
# runner, which joined COMMIT_SHA and BRANCH into one header line.
$normalizedRows = New-Object 'System.Collections.Generic.List[string]'
foreach ($line in $rawRows) {
    if ($line -match '^(COMMIT_SHA=[0-9a-f]{40})\s+(BRANCH=[^\s]+)$') {
        [void]$normalizedRows.Add($Matches[1])
        [void]$normalizedRows.Add($Matches[2])
    }
    else {
        [void]$normalizedRows.Add($line)
    }
}
$rows = $normalizedRows.ToArray()

# Construct the marker set explicitly; do not use a comma/concatenation array
# expression, which collapsed the expected markers into one string.
$required = New-Object 'System.Collections.Generic.List[string]'
[void]$required.Add('COMMIT_SHA=' + $CommitSha)
[void]$required.Add('BRANCH=' + $ExpectedBranch)
[void]$required.Add('LOCAL_MOCK_API_SYNTAX=PASS')
[void]$required.Add('LOCAL_MOCK_API_SMOKE=PASS')
[void]$required.Add('PLAYWRIGHT_REUSE_CONFIG=PASS')
[void]$required.Add('NPM_CI=PASS')
[void]$required.Add('TYPECHECK=PASS')
[void]$required.Add('PRODUCTION_BUILD=PASS')
[void]$required.Add('TARGETED_PLAYWRIGHT=PASS')
[void]$required.Add('FULL_PLAYWRIGHT=PASS')
[void]$required.Add('SOURCE_CLEAN_POST=PASS')
[void]$required.Add('FAILURE=')
foreach ($row in $required.ToArray()) {
    if ($rows -cnotcontains $row) {
        throw ('H06_3_POSTFLIGHT_MISSING_MARKER=' + $row)
    }
}
Write-Host 'POSTFLIGHT_REQUIRED_MARKERS=PASS'

$entries = @($rows | Where-Object { $_.StartsWith('FILE_SHA256=') })
if ($entries.Count -lt 5) { throw 'H06_3_POSTFLIGHT_INSUFFICIENT_ARTIFACTS' }
$recorded = @{}
foreach ($entry in $entries) {
    $fields = $entry.Substring('FILE_SHA256='.Length) -split '\|', 2
    if ($fields.Count -ne 2 -or $fields[1] -notmatch '^[0-9a-f]{64}$') {
        throw 'H06_3_POSTFLIGHT_INVALID_FILE_HASH_RECORD'
    }
    $rel = $fields[0]
    if ($rel -match '(^|[\\/])\.\.([\\/]|$)' -or
        [System.IO.Path]::IsPathRooted($rel) -or [string]::IsNullOrWhiteSpace($rel)) {
        throw 'H06_3_POSTFLIGHT_UNSAFE_ARTIFACT_PATH'
    }
    if ($recorded.ContainsKey($rel)) { throw 'H06_3_POSTFLIGHT_DUPLICATE_ARTIFACT' }
    $path = Join-Path $Evidence $rel
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
        throw ('H06_3_POSTFLIGHT_FILE_MISSING=' + $rel)
    }
    $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($hash -cne $fields[1]) { throw ('H06_3_POSTFLIGHT_FILE_SHA256_MISMATCH=' + $rel) }
    $recorded[$rel] = $true
}

$actualFiles = @(Get-ChildItem -LiteralPath $Evidence -Recurse -File |
    Where-Object { $_.Name -notin @('manifest.txt', 'manifest.sha256') })
foreach ($file in $actualFiles) {
    $rel = $file.FullName.Substring($Evidence.Length).TrimStart('\')
    if (-not $recorded.ContainsKey($rel)) {
        throw ('H06_3_POSTFLIGHT_UNRECORDED_ARTIFACT=' + $rel)
    }
}
if ($actualFiles.Count -ne $recorded.Count) { throw 'H06_3_POSTFLIGHT_ARTIFACT_COUNT_MISMATCH' }
Write-Host 'POSTFLIGHT_ALL_FILE_HASHES=PASS'

$head = (& $GitExe -C $Work rev-parse HEAD | Out-String).Trim()
if ($LASTEXITCODE -ne 0 -or $head -cne $CommitSha) {
    throw 'H06_3_POSTFLIGHT_EXACT_SOURCE_MISMATCH'
}
$branch = (& $GitExe -C $Work branch --show-current | Out-String).Trim()
if ($LASTEXITCODE -ne 0 -or $branch -cne $ExpectedBranch) {
    throw 'H06_3_POSTFLIGHT_BRANCH_MISMATCH'
}
$dirty = @(& $GitExe -C $Work status --porcelain --untracked-files=all)
if ($LASTEXITCODE -ne 0 -or $dirty.Count -ne 0) {
    throw 'H06_3_POSTFLIGHT_DIRTY_SOURCE'
}
Write-Host 'POSTFLIGHT_SOURCE_CLEAN=PASS'

$remoteLines = @(& $GitExe -C $Work ls-remote --heads origin ('refs/heads/' + $ExpectedBranch))
if ($LASTEXITCODE -ne 0 -or $remoteLines.Count -ne 1) {
    throw 'H06_3_POSTFLIGHT_REMOTE_LOOKUP_FAILED'
}
$remoteSha = ($remoteLines[0] -split '\s+')[0]
if ($remoteSha -cne $CommitSha) {
    throw 'H06_3_POSTFLIGHT_REMOTE_SHA_MISMATCH'
}
Write-Host 'POSTFLIGHT_REMOTE_SHA=PASS'
Write-Host ('COMMIT_SHA=' + $CommitSha)
Write-Host ('MANIFEST_SHA256=' + $actualHash)
Write-Host 'H06_3_INDEPENDENT_POSTFLIGHT=PASS'
